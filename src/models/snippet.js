import mongoose from "mongoose";

const snippetSchema = new mongoose.Schema(
  {
    userId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "User",
    },
    title: {
      type: String,
      required: true,
      trim: true,
    },
    description: {
      type: String,
      required: true,
      trim: true,
    },
  },
  { timestamps: true }
);

const Snippet =
  mongoose.models?.Snippet || mongoose.model("Snippet", snippetSchema);

export default Snippet;
